import { beforeEach, expect, it, vi } from 'vitest'
import { createPinia, setActivePinia } from 'pinia'
import { useAuthStore } from './auth'
const mocks = vi.hoisted(() => ({ enterTenant: vi.fn<(id: number) => Promise<unknown>>(), exitTenant: vi.fn(), refresh: vi.fn(), clear: vi.fn() }))
vi.mock('@/services/auth.service', () => ({ authService: mocks }))
vi.mock('@/services/service-cache', () => ({ clearAllRegisteredCaches: mocks.clear }))
const token = (tenantId: number, delegated = false) => `header.${btoa(JSON.stringify({sub:'1', tenantId, role:'admin', isPlatformAdmin:true, ...(delegated ? {actingTenantId:tenantId, platformTenantId:1} : {})}))}.signature`
const storage = () => {
  const values = new Map<string,string>()
  return { getItem: (k:string) => values.get(k) ?? null, setItem: (k:string,v:string) => values.set(k,v), removeItem: (k:string) => values.delete(k) }
}
beforeEach(() => {
  vi.resetAllMocks()
  vi.stubGlobal('localStorage', storage())
  vi.stubGlobal('sessionStorage', storage())
  vi.stubGlobal('window', {dispatchEvent:vi.fn()})
  localStorage.setItem('na_access_token', token(1))
  localStorage.setItem('na_refresh_token', 'refresh-original')
  mocks.enterTenant.mockImplementation((id:number) => Promise.resolve({data:{accessToken:token(id,true),tenant:{id,name:`Tenant ${id}`,slug:`t${id}`}}}))
  mocks.exitTenant.mockResolvedValue({})
  setActivePinia(createPinia())
})
it('selecting the original tenant is a no-op without delegation or cache resets', async () => {
  const auth = useAuthStore()
  await auth.enterTenantManagement(1)
  expect(auth.isManagingTenant).toBe(false)
  expect(mocks.enterTenant).not.toHaveBeenCalled()
  expect(mocks.clear).not.toHaveBeenCalled()
})
it('returns home by restoring the exact original token and clearing delegated storage', async () => {
  const auth = useAuthStore()
  await auth.enterTenantManagement(2)
  expect(auth.isManagingTenant).toBe(true)
  await auth.enterTenantManagement(1)
  expect(mocks.enterTenant).toHaveBeenCalledTimes(1)
  expect(mocks.exitTenant).toHaveBeenCalledWith(2)
  expect(auth.accessToken).toBe(token(1))
  expect(auth.user?.tenantId).toBe(1)
  expect(auth.isManagingTenant).toBe(false)
  expect(auth.managedTenant).toBeNull()
  expect(localStorage.getItem('na_platform_access_token')).toBeNull()
  expect(localStorage.getItem('na_managed_tenant')).toBeNull()
  expect(auth.refreshToken).toBe('refresh-original')
  expect(mocks.clear).toHaveBeenCalledTimes(2)
})
it('preserves the original identity across multiple managed tenants', async () => {
  const auth = useAuthStore()
  for (const id of [2,3,2]) await auth.enterTenantManagement(id)
  await auth.enterTenantManagement(1)
  expect(auth.accessToken).toBe(token(1))
  expect(auth.isManagingTenant).toBe(false)
  expect(mocks.enterTenant.mock.calls.map(c => c[0])).toEqual([2,3,2])
})
it.each([403,500])('failed entry (%s) leaves original authentication untouched', async status => {
  const auth = useAuthStore()
  mocks.enterTenant.mockRejectedValue({response:{status}})
  await expect(auth.enterTenantManagement(2)).rejects.toMatchObject({response:{status}})
  expect(auth.accessToken).toBe(token(1))
  expect(localStorage.getItem('na_platform_access_token')).toBeNull()
  expect(auth.isManagingTenant).toBe(false)
  expect(mocks.clear).not.toHaveBeenCalled()
})
it('failed switch from another managed tenant preserves that context and home token', async () => {
  const auth = useAuthStore()
  await auth.enterTenantManagement(2)
  mocks.enterTenant.mockRejectedValue(new Error('offline'))
  await expect(auth.enterTenantManagement(3)).rejects.toThrow('offline')
  expect(auth.user?.tenantId).toBe(2)
  expect(auth.isManagingTenant).toBe(true)
  await auth.enterTenantManagement(1)
  expect(auth.accessToken).toBe(token(1))
})
it('restores home even when the best-effort exit notification fails', async () => {
  const auth = useAuthStore()
  await auth.enterTenantManagement(2)
  mocks.exitTenant.mockRejectedValue(new Error('offline'))
  await auth.enterTenantManagement(1)
  expect(auth.isManagingTenant).toBe(false)
  expect(auth.accessToken).toBe(token(1))
})
it('restores a persisted self-delegated session using the saved original token', async () => {
  localStorage.setItem('na_access_token',token(1,true))
  localStorage.setItem('na_platform_access_token',token(1))
  const auth = useAuthStore()
  expect(auth.isManagingTenant).toBe(true)
  await auth.enterTenantManagement(1)
  expect(auth.isManagingTenant).toBe(false)
  expect(auth.accessToken).toBe(token(1))
})
it('uses the original tenant identity rather than assuming tenant ID 1 is home', async () => {
  localStorage.setItem('na_access_token',token(7))
  const auth = useAuthStore()
  await auth.enterTenantManagement(1)
  expect(auth.isManagingTenant).toBe(true)
  await auth.enterTenantManagement(7)
  expect(auth.accessToken).toBe(token(7))
  expect(auth.isManagingTenant).toBe(false)
  expect(mocks.enterTenant).toHaveBeenCalledOnce()
  expect(mocks.enterTenant).toHaveBeenCalledWith(1)
})
