const assert = require('node:assert/strict')
module.exports = async ({page}) => {
 const container=page.locator('[data-terminal-container]').first(), panel=page.locator('[data-connection-diagnostic]')
 await container.waitFor(); await page.waitForTimeout(250)
 assert.equal(await panel.count(),0)
 const before=await container.boundingBox()
 const socketCount=await page.evaluate(()=>window.__terminalExperience.sockets.length)
 const emit=(msg)=>page.evaluate(msg=>window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')).at(-1).emitControl(msg),msg)
 for(const [code,stage] of [['DNS_FAILED','Resolução do destino'],['HOST_PORT_REFUSED','Acesso à porta do destino'],['AUTH_FAILED','Autenticação no destino'],['BASTION_AUTH_FAILED','Autenticação no bastion'],['AGENT_REQUIRED_USER','Disponibilidade do agente pessoal'],['CREDENTIAL_ERROR','Obtenção da credencial'],['UNKNOWN_CODE','Etapa não informada']]){
   await emit({type:'error',code,message:'sensitive-debug=do-not-copy'})
   await panel.getByText(`Etapa: ${stage}`,{exact:true}).waitFor()
   assert.deepEqual(await container.boundingBox(),before)
   assert.equal((await panel.innerText()).includes('sensitive-debug'),false)
 }
 await panel.getByText('Referência para o suporte',{exact:true}).click()
 await panel.getByRole('button',{name:'Copiar referência',exact:true}).click()
 await panel.getByText('Referência copiada.',{exact:true}).waitFor()
 assert.ok((await page.evaluate(()=>window.__terminalExperience.clipboardText)).includes('UNKNOWN_CODE'))
 await page.evaluate(()=>Object.defineProperty(navigator.clipboard,'writeText',{configurable:true,value:async()=>{throw new Error('denied')}}))
 await panel.getByRole('button',{name:'Copiar referência',exact:true}).click()
 await panel.getByText(/Não foi possível copiar/).waitFor()
 await panel.getByRole('button',{name:'Recolher diagnóstico',exact:true}).click()
 await panel.getByRole('button',{name:'Ver diagnóstico do acesso',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 await page.waitForTimeout(250)
 const rect=await panel.boundingBox();assert.ok(rect.x>=0 && rect.x+rect.width<=390)
 const colors=await panel.getByRole('button',{name:'Recolher diagnóstico',exact:true}).evaluate(el=>({color:getComputedStyle(el).color,background:getComputedStyle(el).backgroundColor}))
 assert.equal(colors.color,'rgb(229, 231, 235)');assert.equal(colors.background,'rgb(31, 41, 55)')
 await page.screenshot({path:`/tmp/nodeaccess-connection-diagnostic-${process.env.UI_THEME||'dark'}.png`})
 assert.equal(await page.evaluate(()=>window.__terminalExperience.sockets.length),socketCount)
 // User explicitly reconnects. A successful new attempt must remove all old diagnostic state.
 await panel.getByRole('button',{name:'Recolher diagnóstico',exact:true}).click()
 await page.setViewportSize({width:1440,height:900})
 const reconnect=page.locator('[data-terminal-pane-toolbar]').getByRole('button',{name:'↺ Reconectar',exact:true})
 if(await reconnect.count()) await reconnect.click()
 else await page.locator('[data-terminal-action="show-toolbar"]').click().then(()=>reconnect.click())
 await panel.waitFor({state:'hidden'})
 await page.waitForTimeout(150)
 await emit({type:'closed'})
 assert.equal(await panel.count(),0,'Normal exit is not a connection failure')
 await reconnect.click(); await page.waitForTimeout(150)
 await page.evaluate(()=>window.__dropLatestSsh())
 await panel.getByText('Etapa: Comunicação com NodeAccess',{exact:true}).waitFor()
 const afterDrop=await page.evaluate(()=>window.__terminalExperience.sockets.length)
 await page.waitForTimeout(300)
 assert.equal(await page.evaluate(()=>window.__terminalExperience.sockets.length),afterDrop)
 return {socketInterruption:true,passed:true,codes:7,geometryPreserved:true,manualRecovery:true,normalExit:true,referenceRedacted:true,clipboardFailure:true,mobile:true}
}
