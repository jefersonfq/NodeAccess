const fs = require('node:fs')
const out = '/tmp/nodeaccess-file-utilities-ui'
module.exports = async function ({ page, context }) {
  fs.mkdirSync(out, { recursive: true })
  await page.evaluate(() => { window.__terminalExperience.reviewFiles = true; window.__terminalExperience.fileUtilitiesReview = true })
  const requests = () => page.evaluate(() => window.__terminalExperience.sent.flatMap(raw => { try { const m = JSON.parse(raw); return m.type === 'sftp_utility' ? [m] : [] } catch { return [] } }))
  if ((await requests()).length) throw new Error('Utilities requested work while closed')
  await page.locator('[data-terminal-rail-action="files"]').click()
  await page.getByText('review.conf', { exact: true }).waitFor()
  async function open(label) {
    await page.getByRole('button', { name: /Ações.*review.conf/ }).click()
    await page.getByText(label, { exact: true }).click()
    await page.getByLabel('Arquivo (caminho completo)', { exact: true }).waitFor()
  }
  await open('Copiar para outro host')
  const input = page.getByLabel('Arquivo (caminho completo)', { exact: true })
  if (await input.inputValue() !== '/root/review.conf') throw new Error('Selected file context not reused')
  await page.locator('.n-modal .n-base-selection:not(.n-base-selection--disabled)').click()
  await page.getByText(/Destino pessoal · alice@192\.0\.2\.20/).click()
  await page.getByRole('button', { name: 'Copiar arquivo', exact: true }).click()
  await page.getByText('Arquivo copiado para /home/alice/review.conf usando a conta alice.', { exact: true }).waitFor()
  const copy = (await requests()).find(m => m.operation === 'copy')
  if (copy.directory || copy.path !== '/root/review.conf' || copy.targetSessionId !== 99200) throw new Error('Copy did not reuse path, home and authenticated destination')
  await input.fill('/root/large.tar')
  await page.getByRole('button', { name: 'Copiar arquivo', exact: true }).click()
  await page.getByText('Arquivo maior que 2 MiB. Use o comando direto.', { exact: true }).waitFor()
  await page.getByText('Comando direto', { exact: true }).click()
  await page.getByRole('button', { name: 'Preparar comando', exact: true }).click()
  await page.getByRole('textbox', { name: 'Comando preparado' }).waitFor()
  const command = await page.getByRole('textbox', { name: 'Comando preparado' }).inputValue()
  const sentInput = await page.evaluate(() => window.__terminalExperience.inputSent.join(''))
  if (sentInput.includes('scp ')) throw new Error('Prepared command executed without user action')
  await page.screenshot({ path: `${out}/copy-command.png` })
  const baseHost = await page.evaluate(() => fetch('/api/v1/hosts/9401').then(response => response.json()))
  const newHost = { ...baseHost, id: 9501, name: 'Destino novo', ip: '192.0.2.21', sshUser: '' }
  await context.route('**/api/v1/hosts?*', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ data: [newHost], total: 1, page: 1, limit: 20 }) }))
  await context.route('**/api/v1/hosts/9501', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(newHost) }))
  // A previous credential challenge in the source must not fill another tab.
  await page.evaluate(() => window.__terminalExperience.sockets.find(socket => socket.url.includes('/ws/ssh/9401')).emitControl({ type: 'credentials_required', hostId: 9401, hostName: 'terminal-critical-host', needsUsername: true, needsPassword: true }))
  await page.locator('#cred-username-input input').fill('source-user')
  await page.locator('#cred-password-input input').fill('fixture-source-password')
  await page.getByRole('button', { name: 'Conectar', exact: true }).click()
  await page.getByText('Conectar outro host', { exact: true }).click()
  await page.getByPlaceholder('Nome ou IP do host').fill('Destino novo')
  await page.getByText('Destino novo · 192.0.2.21', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Conectar', exact: true }).click()
  await page.locator('#cred-username-input input').waitFor()
  if (await page.locator('#cred-username-input input').inputValue()) throw new Error('Another tab reused source credentials')
  await page.locator('#cred-username-input input').fill('destination-user')
  await page.locator('#cred-password-input input').fill('fixture-destination-password')
  await page.screenshot({ path: `${out}/missing-credentials.png` })
  await page.getByRole('button', { name: 'Conectar', exact: true }).last().click()
  await page.getByText(/Destino novo · destination-user@192\.0\.2\.21/).first().waitFor()
  await page.getByRole('textbox', { name: 'Comando preparado' }).waitFor()

  await page.getByRole('button', { name: 'Fechar painel', exact: true }).click()
  await open('Editar no aplicativo local')
  await page.getByRole('button', { name: 'Abrir editor local', exact: true }).click()
  const state = async value => page.evaluate(value => window.__terminalExperience.sockets.find(s => s.url.includes('/ws/ssh/9401')).emitControl({ type: 'sftp_edit_event', path: '/root/review.conf', editId: '11111111-1111-4111-8111-111111111111', state: value }), value)
  await state('synced'); await page.getByText('Sincronizado com o servidor.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Fechar painel', exact: true }).click()
  await open('Editar no aplicativo local')
  await page.getByRole('button', { name: 'Encerrar edição', exact: true }).waitFor()
  await page.evaluate(() => window.__terminalExperience.sockets.find(socket => socket.url.includes('/ws/ssh/9401')).emitControl({ type: 'sftp_edit_event', path: '/root/review.conf', state: 'error', code: 'FILE_BACKUP_QUOTA' }))
  await page.getByText('Limite de backups atingido. Preserve a cópia local e revise os backups no servidor antes de tentar novamente.', { exact: true }).waitFor()
  await state('conflict'); await page.getByText(/O arquivo remoto mudou/).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  const modal = await page.getByRole('dialog').last().boundingBox()
  if (!modal || modal.x < 0 || modal.x + modal.width > 391) throw new Error('Utility modal overflows mobile')
  await page.screenshot({ path: `${out}/edit-conflict-mobile.png` })
  await page.getByRole('button', { name: 'Encerrar edição', exact: true }).click()
  await page.getByText('Edição encerrada. A cópia local foi preservada.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Fechar painel', exact: true }).click()
  await page.evaluate(() => { window.__terminalExperience.editorUnavailable = true })
  await open('Editar no aplicativo local')
  await page.getByText(/Conecte ou atualize seu agente pessoal Windows/).waitFor()
  if (await page.getByRole('button', { name: 'Abrir editor local', exact: true }).isEnabled()) throw new Error('Unavailable agent still permits opening editor')
  await page.getByRole('button', { name: 'Fechar painel', exact: true }).click()
  const errors = await page.evaluate(() => window.__terminalExperience.errors)
  if (errors.length) throw new Error(errors.join('\n'))
  return { passed: true, idleWithoutRequests: true, selectedPathReused: true, destinationIdentityVisible: true, homeDefault: true, oversizedCopyRecovery: true, commandWithoutExecution: true, externalEditStatus: true, backupQuotaExplained: true, editSurvivesPanelClose: true, conflictVisible: true, mobileFits: true, stopEditing: true, missingCredentialsRequested: true, credentialsScopedToTab: true, backgroundDestinationConnection: true, unavailableAgentExplained: true, command, requests: await requests(), screenshots: out, errors }
}
