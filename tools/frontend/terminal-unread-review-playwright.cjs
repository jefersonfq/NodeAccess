const assert = require('node:assert/strict')
module.exports = async ({page}) => {
  await page.evaluate(async () => {
    await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/hosts')
  })
  await page.locator('[data-open-sessions-panel]').waitFor()
  const badge=page.getByTestId('open-session-unread').first()
  const emit=async n=>page.evaluate(async n=>{
    const ws=window.__terminalExperience.sockets.find(s=>s.url.includes('/ws/ssh/')&&s.readyState===1)
    for(let i=0;i<n;i++){ ws.emitBytes(`unseen output ${i}\r\n`); await new Promise(resolve=>setTimeout(resolve,35)) }
  },n)
  await emit(1);await page.waitForFunction(()=>document.querySelector('[data-testid="open-session-unread"]')?.textContent.trim()==='1')
  await badge.hover()
  await page.locator('.n-tooltip').filter({hasText:'não é uma contagem de comandos, sessões ou usuários'}).waitFor()
  await emit(2);await page.waitForFunction(()=>document.querySelector('[data-testid="open-session-unread"]')?.textContent.trim()==='3')
  await emit(100);await page.waitForFunction(()=>document.querySelector('[data-testid="open-session-unread"]')?.textContent.trim()==='99+')
  assert.match(await badge.getAttribute('aria-label'),/^103 atualizações/)
  await badge.locator('xpath=ancestor::button[1]').focus();assert.equal(await badge.evaluate(el=>el.closest('button')===document.activeElement),true)
  assert.match(await badge.locator('xpath=ancestor::button[1]').getAttribute('aria-label'),/103 atualizações/)
  const count=await page.evaluate(()=>window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')).length)
  await page.locator('[data-open-sessions-panel] button').filter({hasText:'terminal-critical-host'}).first().click()
  await page.waitForURL('**/terminal')
  await page.evaluate(async()=>{await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/hosts')})
  await page.locator('[data-open-sessions-panel]').waitFor()
  assert.equal(await page.getByTestId('open-session-unread').count(),0)
  assert.equal(await page.evaluate(()=>window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')).length),count)
  // Open a second real terminal pane using the user's tab menu.
  await page.locator('[data-open-sessions-panel] button').filter({hasText:'terminal-critical-host'}).first().click()
  await page.waitForURL('**/terminal')
  await page.locator('.terminal-tab').first().click({button:'right'})
  await page.getByText('Duplicar aba',{exact:true}).click()
  await page.waitForFunction(()=>window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')&&s.readyState===1).length===2)
  await page.evaluate(async()=>{await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/hosts')})
  await page.waitForFunction(()=>document.querySelectorAll('[data-open-session-host-id]').length===2)
  assert.equal(await page.getByTestId('open-session-unread').count(),0,'Creating a tab must not increment another tab')
  await page.evaluate(async()=>{
    const sockets=window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')&&s.readyState===1)
    sockets[0].emitBytes('first tab output\r\n');await new Promise(r=>setTimeout(r,80))
    sockets[0].emitBytes('more output\r\n');sockets[1].emitBytes('second tab output\r\n')
  })
  await page.waitForFunction(()=>[...document.querySelectorAll('[data-testid="open-session-unread"]')].map(e=>e.textContent.trim()).join(',')==='2,1')
  const cards=page.locator('[data-open-session-host-id]')
  await cards.first().getByRole('button',{name:'✕',exact:true}).click()
  await page.waitForFunction(()=>document.querySelectorAll('[data-open-session-host-id]').length===1)
  assert.equal((await page.getByTestId('open-session-unread').innerText()).trim(),'1')
  await page.evaluate(()=>{
    const old=window.__terminalExperience.sockets.find(s=>s.url.includes('/ws/ssh/'))
    old.emitBytes('late output from closed tab\r\n')
  })
  await page.waitForTimeout(100)
  assert.equal(await cards.count(),1)
  assert.equal((await page.getByTestId('open-session-unread').innerText()).trim(),'1')
  await cards.first().getByRole('button').filter({hasText:'terminal-critical-host'}).click()
  await page.waitForURL('**/terminal')
  await page.evaluate(()=>window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')&&s.readyState===1).at(-1).emitBytes('visible output\r\n'))
  await page.waitForTimeout(100)
  await page.evaluate(async()=>{await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/hosts')})
  await page.locator('[data-open-sessions-panel]').waitFor()
  assert.equal(await page.getByTestId('open-session-unread').count(),0,'Output in the viewed tab must not remain unread')
  return {unreadSequence:[1,3,103],badgeCap:'99+',tooltip:true,keyboardLabel:true,resetOnViewing:true,reconnection:false,twoTabsIndependent:true,lateClosedOutputIgnored:true,visibleOutputNotUnread:true}
}
