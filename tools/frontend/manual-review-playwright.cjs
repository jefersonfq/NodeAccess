const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
module.exports = async ({page,context}) => {
  const out='/tmp/nodeaccess-manual-review';await fs.mkdir(out,{recursive:true})
  let enabled=false,failSave=false,failRead=false
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await context.route('**/api/v1/settings/manual',route=>{
    if(route.request().method()==='PATCH') {
      if(failSave)return route.fulfill({status:500,json:{message:'simulated save error'}})
      enabled=route.request().postDataJSON().enabled;return route.fulfill({json:{enabled}})
    }
    return route.fulfill(failRead?{status:503,json:{message:'simulated unavailable'}}:{json:{enabled}})
  })
  await context.route('**/api/v1/settings',route=>route.fulfill({json:{tenant:{id:1,name:'Organização exemplo',slug:'demo'},license:{maxUsers:50,maxHosts:100,activeUsers:1,registeredHosts:1,featureEntitlements:{},integrationEntitlements:{}},sessionLimits:{maxPerUser:null,maxPerTenant:null},passwordPolicy:{minLength:12,regex:'.*',description:''},tenantSettings:{totpIssuer:'NodeAccess',hostsDefaultView:'home'}}}))
  const navigate = url=>page.evaluate(async url=>{await document.querySelector('#app').__vue_app__.config.globalProperties.$router.push(url)},url)
  const sockets=()=>page.evaluate(()=>window.__terminalExperience.sockets.filter(s=>s.url.includes('/ws/ssh/')).length)
  const originalSockets=await sockets()
  const dismissPreset=page.getByRole('button',{name:'Agora não',exact:true})
  if(await dismissPreset.count()) await dismissPreset.click()
  await navigate('/hosts');await page.locator('[data-open-sessions-panel]').waitFor()
  assert.equal(await page.locator('[data-manual-link]').count(),0)
  await page.getByRole('button',{name:'Ajuda',exact:true}).waitFor()
  await navigate('/manual');await page.getByText('Manual ainda não habilitado neste tenant',{exact:true}).waitFor()
  assert.equal(await page.locator('.manual-prose').count(),0)
  await navigate('/admin/settings')
  const toggle=page.locator('[data-manual-settings]').getByRole('switch')
  await toggle.waitFor();await toggle.click()
  await page.waitForFunction(()=>document.querySelector('[data-manual-settings] [role="switch"]')?.getAttribute('aria-checked')==='true')
  await navigate('/hosts');await page.locator('[data-manual-link="hosts"]').waitFor()
  assert.equal(await page.getByRole('button',{name:'Ajuda',exact:true}).count(),0,'Existing pilot help must not compete with the manual')
  await page.waitForTimeout(500)
  await page.screenshot({path:path.join(out,'hosts.png')})
  const popupPromise=context.waitForEvent('page')
  await page.locator('[data-manual-link="hosts"]').click()
  const help=await popupPromise
  await help.waitForURL('**/manual/hosts');await help.locator('.manual-prose').waitFor()
  assert.ok((await help.locator('[data-manual-version]').innerText()).includes(process.env.MANUAL_EXPECTED_VERSION || '9.8.7-manual-test'))
  assert.equal(await sockets(),originalSockets,'Opening help must not reconnect the terminal')
  await help.close()
  await navigate('/terminal');await page.locator('[data-manual-link="terminal"]').waitFor()
  assert.equal(await page.locator('[data-terminal-display-help]').count(),0)
  if (!await page.locator('[data-terminal-action="highlights"]').count()) await page.locator('[data-terminal-action="show-toolbar"]').click()
  await page.locator('[data-terminal-action="highlights"]').click()
  await page.locator('[data-terminal-highlight-controls]').waitFor()
  await page.waitForTimeout(250)
  await page.screenshot({path:path.join(out,'terminal.png')})
  await page.locator('[data-terminal-action="highlights"]').click()
  await page.locator('[data-terminal-rail-action="files"]').click()
  await page.locator('[data-manual-link="sftp"]').waitFor()
  await page.locator('[data-terminal-sidebar-header]').getByRole('button',{name:'⛶',exact:true}).click()
  await page.waitForURL('**/files/*')
  await page.locator('[data-manual-link="sftp"]').waitFor()
  await page.getByText('SFTP conectado', {exact:true}).waitFor()
  await page.getByRole('button', {name:'＋ Nova pasta',exact:true}).waitFor()
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).find(button => button.textContent.includes('Nova pasta'))?.disabled)
  await page.waitForTimeout(500)
  await page.screenshot({path:path.join(out,'sftp.png')})
  await navigate('/manual')
  await page.locator('.manual-cards').waitFor()
  assert.equal(await page.locator('.manual-card').count(),5)
  await page.waitForTimeout(500)
  const contrast=await page.evaluate(()=>{
    const luminance=color=>{const c=color.match(/[\d.]+/g).slice(0,3).map(Number).map(v=>v/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4);return .2126*c[0]+.7152*c[1]+.0722*c[2]}
    const ratio=(a,b)=>{const values=[luminance(a),luminance(b)].sort((x,y)=>y-x);return (values[0]+.05)/(values[1]+.05)}
    const page=document.querySelector('.manual-page'),lead=document.querySelector('.manual-lead'),card=document.querySelector('.manual-card')
    return {lead:ratio(getComputedStyle(lead).color,getComputedStyle(page).backgroundColor),card:ratio(getComputedStyle(card).color,getComputedStyle(card).backgroundColor)}
  })
  assert.ok(contrast.lead>=4.5&&contrast.card>=4.5,`Insufficient manual contrast: ${JSON.stringify(contrast)}`)
  await page.screenshot({path:path.join(out,`index-${process.env.UI_THEME||'dark'}.png`)})
  const search=page.getByRole('textbox',{name:'Buscar procedimento ou dúvida…'})
  await search.fill('revogacao');await page.getByRole('link',{name:/Compartilhamento de sessão ao vivo/}).first().waitFor()
  await search.fill('xyz-no-result');await page.getByText('Nenhum guia encontrado.',{exact:false}).first().waitFor()
  await search.clear()
  for(const id of ['hosts','terminal','sharing','sftp','tenants']){
    await page.locator(`[data-manual-chapter="${id}"]`).click()
    await page.waitForURL(`**/manual/${id}`)
    await page.locator(`.manual-figure img[src$="/${id}.png"]`).waitFor()
    await page.locator('.manual-prose').waitFor()
    assert.ok((await page.locator('.manual-prose').innerText()).includes('Resultado esperado'))
    assert.equal(await page.locator('.manual-flow').evaluate(el=>el.complete&&el.naturalWidth>0),true)
    const illustration=page.locator('.manual-figure button')
    await illustration.scrollIntoViewIfNeeded()
    await page.locator('.manual-figure img').evaluate(img=>img.decode())
    await illustration.click();assert.equal(await illustration.getAttribute('aria-expanded'),'true')
    await illustration.click();assert.equal(await illustration.getAttribute('aria-expanded'),'false')
  }
  await navigate('/manual/sharing');await page.waitForTimeout(500);await page.evaluate(()=>{const original=window.open;window.open=function(...args){const popup=original.apply(this,args);return popup?{document:popup.document,set opener(value){popup.opener=value},get closed(){return popup.closed},print:()=>{},close:()=>popup.close()}:popup}});const printing=context.waitForEvent('page');await page.getByRole('button',{name:'Imprimir / PDF',exact:true}).click();const printPage=await printing;await printPage.getByText('Resultado esperado',{exact:true}).waitFor();await printPage.waitForFunction(()=>Array.from(document.images).every(img=>img.complete&&img.naturalWidth>0),{},{timeout:15000});await printPage.pdf({path:path.join(out,'sharing-print.pdf'),format:'A4',printBackground:true});await printPage.close();await page.screenshot({path:path.join(out,`article-${process.env.UI_THEME||'dark'}.png`),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(500)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'Manual must not overflow mobile viewport')
  await page.screenshot({path:path.join(out,`mobile-${process.env.UI_THEME||'dark'}.png`),fullPage:true})
  await page.setViewportSize({width:1440,height:900})
  await navigate('/manual/missing-chapter');await page.getByText('Este capítulo não foi encontrado',{exact:true}).waitFor()
  await navigate('/admin/settings');failSave=true;await toggle.click()
  await page.getByText('Não foi possível confirmar o salvamento. Confira a configuração atual ou tente novamente.',{exact:true}).waitFor()
  assert.equal(await toggle.getAttribute('aria-checked'),'true')
  failSave=false;await toggle.click()
  await page.waitForFunction(()=>document.querySelector('[data-manual-settings] [role="switch"]')?.getAttribute('aria-checked')==='false')
  await navigate('/manual/hosts');await page.getByText('Manual ainda não habilitado neste tenant',{exact:true}).waitFor()
  failRead=true
  // A fresh page exercises unavailable configuration without touching the live terminal's document.
  const failure=await context.newPage();await failure.goto(page.url(),{waitUntil:'domcontentloaded'})
  await failure.getByText('Não foi possível consultar a disponibilidade do manual.',{exact:true}).waitFor()
  failRead=false;enabled=true;await failure.getByRole('button',{name:'Tentar novamente',exact:true}).click()
  await failure.locator('.manual-prose').waitFor();await failure.close()
  assert.equal(await sockets(),originalSockets)
  assert.deepEqual(errors,[])
  return {passed:true,chapters:5,disabledByDefault:true,adminToggle:true,helpIntegrated:true,popupWithoutReconnection:true,versionMatchesBuild:true,search:true,mobile:true,saveFailure:true,readFailureRetry:true,unknownChapter:true,screenshots:out}
}
